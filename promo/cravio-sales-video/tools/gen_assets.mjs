// Extracts vector data from the brand SVGs into a TS module for Remotion.
// Geometry is copied verbatim; only stroke-width on icons becomes a token so
// the stroke can be re-weighted when the 24px icons are scaled up.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const icons = {};
for (const f of fs.readdirSync(path.join(root, 'assets/icons')).filter((f) => f.endsWith('.svg'))) {
  const s = fs.readFileSync(path.join(root, 'assets/icons', f), 'utf8');
  const inner = s.slice(s.indexOf('>', s.indexOf('<svg')) + 1, s.lastIndexOf('</svg>')).trim();
  icons[f.replace('.svg', '')] = inner.replace(/stroke-width="1.75"/g, 'stroke-width="__SW__"').replace(/\s+/g, ' ');
}
const wordmark = (file) => {
  const s = fs.readFileSync(path.join(root, 'assets/logo', file), 'utf8');
  const m = s.match(/<g id="wordmark" transform="translate\(([^,]+),([^)]+)\)">([\s\S]*?)<\/g>/);
  return { x: +m[1], y: +m[2], inner: m[3].trim() };
};
const out = `// GENERATED by tools/gen_assets.mjs from assets/icons and assets/logo. Do not edit.
export const ICONS: Record<string, string> = ${JSON.stringify(icons, null, 1)};
// Outlined wordmark paths, verbatim from the colour-on-dark logo files.
export const WORDMARK_H = ${JSON.stringify(wordmark('cravio-horizontal-colour-on-dark.svg'))};
export const WORDMARK_S = ${JSON.stringify(wordmark('cravio-stacked-colour-on-dark.svg'))};
`;
fs.mkdirSync(path.join(root, 'remotion/src/brand'), { recursive: true });
fs.writeFileSync(path.join(root, 'remotion/src/brand/assets.gen.ts'), out);
console.log('icons', Object.keys(icons).length);
