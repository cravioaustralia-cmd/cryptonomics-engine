#!/usr/bin/env python3
"""Build render inputs for s33:
  - ../transcript.json : Whisper word timings (render/whisper_raw.json) mapped onto the
    script's display words (figures for numbers, script punctuation).
  - map_data.js        : Natural Earth AUS states projected to km (equirectangular,
    lat0 = -27), simplified, plus the hand-placed points from SOURCES.md.
Run: python3 shorts/s33-hutt-river/render/build_data.py
"""
import json, math, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
EP = os.path.dirname(HERE)

DISPLAY = (
    "In 1970, a West Australian farmer quit Australia… without leaving his farm. "
    "Leonard Casley had about 4,000 hectares of wheat ready to harvest. "
    "Then new government quotas let him sell the crop from roughly 40. "
    "So on the 21st of April, he declared his farm an independent country. "
    "The Hutt River Province. 75 square kilometres, about 500 kilometres north of Perth. "
    "He started calling himself Prince Leonard. Printed his own stamps. Minted his own coins. Issued his own passports. "
    "In 1977, he even declared war on Australia… then called it off a few days later. "
    "But no country ever recognised it. And the tax office never stopped counting. "
    "Millions in unpaid tax later, in 2020, his son quietly handed it back. "
    "Fifty years earlier, it all started because…"
).split()


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def build_transcript():
    raw = json.load(open(os.path.join(HERE, "whisper_raw.json")))
    words = []
    for w in raw["words"]:
        if words and re.fullmatch(r",\d{3}\.?", w["word"]):  # "4" ",000"
            words[-1]["word"] += w["word"]
            words[-1]["end"] = w["end"]
        else:
            words.append(dict(w))
    assert len(words) == len(DISPLAY), (len(words), len(DISPLAY))
    alias = {"21st": "21st", "50": "fifty"}
    out = []
    for w, d in zip(words, DISPLAY):
        a, b = norm(w["word"]), norm(d)
        if a != b and alias.get(a, a) != b:
            raise SystemExit(f"mismatch {w['word']!r} vs {d!r}")
        out.append({"word": d, "start": w["start"], "end": w["end"]})
    json.dump({"duration": 48.048, "words": out}, open(os.path.join(EP, "transcript.json"), "w"), indent=1)
    print("transcript words:", len(out))


LAT0 = -27.0
KX = 111.32 * math.cos(math.radians(LAT0))
KY = 110.57


def proj(lon, lat):
    return ((lon - 134.0) * KX, -(lat - LAT0) * KY)


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy) or 1e-9
    dmax, idx = 0, 0
    for i in range(1, len(pts) - 1):
        x, y = pts[i]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / L
        if d > dmax:
            dmax, idx = d, i
    if dmax > eps:
        return rdp(pts[: idx + 1], eps)[:-1] + rdp(pts[idx:], eps)
    return [pts[0], pts[-1]]


def ring_path(ring, eps):
    pts = [proj(*c[:2]) for c in ring]
    # rdp on a closed ring: split in two halves
    h = len(pts) // 2
    s = rdp(pts[: h + 1], eps)[:-1] + rdp(pts[h:], eps)
    if len(s) < 4:
        return ""
    return "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in s) + "Z"


def build_map():
    d = json.load(open(os.path.join(EP, "map", "ne_10m_AUS_admin_1_states_provinces.geojson")))
    states = {}
    for f in d["features"]:
        name = f["properties"]["name"]
        if name in ("Macquarie Island", "Lord Howe Island", "Jervis Bay Territory"):
            continue
        g = f["geometry"]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        eps = 0.6 if name == "Western Australia" else 2.5
        parts = []
        for poly in polys:
            # drop tiny islands
            ring = poly[0]
            xs = [proj(*c[:2]) for c in ring]
            area = abs(sum(xs[i][0] * xs[i - 1][1] - xs[i - 1][0] * xs[i][1] for i in range(len(xs)))) / 2
            if area < (40 if name == "Western Australia" else 300):
                continue
            p = ring_path(ring, eps)
            if p:
                parts.append(p)
        states[name] = "".join(parts)
    pts = {
        "farm": proj(114.47069, -28.07444),
        "northampton": proj(114.63, -28.35),
        "perth": proj(115.86, -31.95),
        "geraldton": proj(114.599971, -28.76663),
        "kalbarri": proj(114.166664, -27.666181),
    }
    js = "/* generated by build_data.py — Natural Earth (PD), km projection lat0=-27 lon0=134 */\n"
    js += "window.S33_MAP = " + json.dumps({"states": states, "pts": {k: [round(v[0], 2), round(v[1], 2)] for k, v in pts.items()}}) + ";\n"
    open(os.path.join(HERE, "map_data.js"), "w").write(js)
    print("map_data.js bytes:", len(js), {k: len(v) for k, v in states.items()})


build_transcript()
build_map()
